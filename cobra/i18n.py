_current = DEFAULT


def set_language(lang):
    global _current
    _current = lang if lang in STRINGS else DEFAULT


def language():
    return _current


def next_language(lang):
    codes = list(LANGUAGES)
    return codes[(codes.index(lang) + 1) % len(codes)] if lang in codes else DEFAULT


def t(key, **kw):
    """Texto no idioma atual (se faltar a tradução, usa o português; se faltar tudo, mostra a chave)."""
    text = STRINGS[_current].get(key) or STRINGS[DEFAULT].get(key) or key
    return text.format(**kw) if kw else text


def detect_language():
    """Idioma do sistema: português se ele estiver em português, senão inglês."""
    for var in ('LANGUAGE', 'LC_ALL', 'LC_MESSAGES', 'LANG'):
        if os.environ.get(var):
            return 'pt' if os.environ[var].lower().startswith('pt') else 'en'
    try:
        code = locale.getlocale()[0] or ''
    except ValueError:
        code = ''
    return 'pt' if code.lower().startswith('pt') else 'en'
